use alloc::vec::Vec;

/// Start of Image
const SOI: u8 = 0xD8;
/// End of Image
const EOI: u8 = 0xD9;

/// JFIF application segment(optional)
const APP0: u8 = 0xE0;

/// Define Quantization Table
const DQT: u8 = 0xDB;
/// Start of Frame, baseline DCT
const SOF0: u8 = 0xC0;
/// Define Huffman Table
const DHT: u8 = 0xC4;
/// Start of scan
const SOS: u8 = 0xDA;

fn write_marker(buf: &mut Vec<u8>, marker: u8) {
    buf.push(0xFF);
    buf.push(marker);
}

fn write_u16_be(buf: &mut Vec<u8>, n: u16) {
    buf.extend_from_slice(&n.to_be_bytes());
}

pub fn write_soi(buf: &mut Vec<u8>) {
    write_marker(buf, SOI);
}

pub fn write_app0(buf: &mut Vec<u8>) {
    write_marker(buf, APP0);

    buf.extend_from_slice(&[
        0x00, 0x10, b'J', b'F', b'I', b'F', 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00,
        0x00,
    ]);
}

pub fn write_dqt(buf: &mut Vec<u8>, luma: &[u8; 64], chroma: &[u8; 64]) {
    write_marker(buf, DQT);
    buf.extend_from_slice(&[0x00, 0x84]);
    buf.push(0x00);
    buf.extend_from_slice(luma);
    buf.push(0x01);
    buf.extend_from_slice(chroma);
}

pub fn write_sof0(buf: &mut Vec<u8>, width: u16, height: u16) {
    write_marker(buf, SOF0);

    write_u16_be(buf, 17);
    buf.push(8);

    write_u16_be(buf, height);
    write_u16_be(buf, width);

    buf.push(3);
    buf.extend_from_slice(&[1, 0x11, 0]);
    buf.extend_from_slice(&[2, 0x11, 1]);
    buf.extend_from_slice(&[3, 0x11, 1]);
}

