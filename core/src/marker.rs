pub fn write_sos(buf: &mut Vec<u8>) {
    write_marker(buf, SOS);

    // Length
    write_u16_be(buf, 12);

    // Number of components
    buf.push(3);

    // Y: DC table 0, AC table 0
    buf.extend_from_slice(&[1, 0x00]);

    // Cb: DC table 1, AC table 1
    buf.extend_from_slice(&[2, 0x11]);

    // Cr: DC table 1, AC table 1
    buf.extend_from_slice(&[3, 0x11]);

    // Spectral selection
    buf.push(0); // Ss
    buf.push(63); // Se

    // Successive approximation
    buf.push(0); // Ah = 0, Al = 0
}

pub fn write_eoi(buf: &mut Vec<u8>) {
    write_marker(buf, EOI);
}
