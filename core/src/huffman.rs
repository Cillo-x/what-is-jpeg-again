pub fn calculate_size_and_amp(raw: i16) -> (u8, u16) {
    if raw == 0 {
        return (0, 0);
    }

    let abs_val = raw.unsigned_abs();
    let size = abs_val.ilog2() + 1;
    let amp = if raw > 0 {
        abs_val
    } else {
        2u16.pow(size) - abs_val - 1
    };

    (size as u8, amp)
}

pub struct HuffmanEncoderTable<const N: usize> {
    pub codes: [u16; N],
    pub sizes: [u8; N],
}

impl<const N: usize> HuffmanEncoderTable<N> {
    pub const fn new(code_lengths: [u8; 16], symbols: &[u16]) -> Self {
        let mut codes = [0u16; N];
        let mut sizes = [0u8; N];
        let mut code: u16 = 0;
        let mut sym_idx = 0;

        let mut i = 0;
        while i < 16 {
            let code_length = (i + 1) as u8;
            let mut j = code_lengths[i];
            while j > 0 {
                let symbol = symbols[sym_idx] as usize;
                sym_idx += 1;
                codes[symbol] = code;
                sizes[symbol] = code_length;
                code += 1;
                j -= 1;
            }
            if i < 15 {
                code <<= 1;
            }
            i += 1;
        }

        HuffmanEncoderTable { codes, sizes }
    }
}

