#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_caculate_size_and_amp() {
        let tests = [
            (-7, (3, 0b000)),
            (-6, (3, 0b001)),
            (-5, (3, 0b010)),
            (-4, (3, 0b011)),
            (4, (3, 0b100)),
            (5, (3, 0b101)),
            (6, (3, 0b110)),
            (7, (3, 0b111)),
        ];

        for t in tests {
            let (raw, expected) = t;
            assert_eq!(calculate_size_and_amp(raw), expected);
        }
    }

    #[test]
    fn test_y_dc_lut() {
        assert_eq!(Y_DC_HFT.sizes[3], 3);
        assert_eq!(Y_DC_HFT.codes[3], 0b100);
    }

    #[test]
    fn test_c_dc_lut() {
        assert_eq!(C_DC_HFT.sizes[6], 6);
        assert_eq!(C_DC_HFT.codes[6], 0b111110);
    }

    #[test]
    fn test_y_ac_lut() {
        // EOB
        assert_eq!(Y_AC_HFT.sizes[0], 4);
        assert_eq!(Y_AC_HFT.codes[0], 0b1010);
        // ZRL
        assert_eq!((Y_AC_HFT.sizes[0xF << 4 | 0]), 11);
        assert_eq!((Y_AC_HFT.codes[0xF << 4 | 0]), 0b1111_1111_001);
        // random choose
        assert_eq!(Y_AC_HFT.sizes[3 << 4 | 8], 16);
        assert_eq!(Y_AC_HFT.codes[3 << 4 | 8], 0b1111_1111_1001_0011)
    }

    #[test]
    fn test_c_ac_lut() {
        //EOB
        assert_eq!(C_AC_HFT.sizes[0], 2);
        assert_eq!(C_AC_HFT.codes[0], 0b00);
        // ZRL
        assert_eq!((C_AC_HFT.sizes[0xF << 4 | 0]), 10);
        assert_eq!((C_AC_HFT.codes[0xF << 4 | 0]), 0b1111_1110_10);
        // random choose
        assert_eq!(C_AC_HFT.sizes[0xC << 4 | 1], 9);
        assert_eq!(C_AC_HFT.codes[0xC << 4 | 1], 0b1111_1101_0);
    }
}
